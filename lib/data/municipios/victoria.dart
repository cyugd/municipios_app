## Historia
La historia de Ciudad Victoria comienza en 1750, cuando fue fundada por José de Escandón bajo el nombre de Villa de Santa María de Aguayo, en honor a la esposa del virrey. Durante la época colonial, fue un centro administrativo y militar de segundo orden, pero su importancia creció tras la Independencia.  
En 1825, adoptó su nombre actual en honor a Guadalupe Victoria, primer presidente de México, y se convirtió en la capital del estado de Tamaulipas.  
Durante el siglo XIX, fue escenario de conflictos como la Guerra de Reforma y la Intervención Francesa, así como de disputas políticas entre liberales y conservadores.  
En el siglo XX, la ciudad experimentó un crecimiento acelerado gracias a la construcción de carreteras, la llegada del ferrocarril, el desarrollo educativo con la fundación de la Universidad Autónoma de Tamaulipas (UAT) en 1950, y la modernización de servicios.  
