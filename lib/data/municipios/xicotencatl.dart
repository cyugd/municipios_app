## Introducción
Xicoténcatl es un municipio con profundas raíces prehispánicas, habitado originalmente por grupos huastecos que aprovechaban el Río Guayalejo para la pesca y la agricultura. Su nombre evoca al héroe tlaxcalteca Xicoténcatl el Joven, aunque la región siempre ha sido un crisol de culturas indígenas. Durante la época colonial, los misioneros franciscanos establecieron templos y haciendas, fomentando el cultivo de la caña de azúcar. En el siglo XIX, el poblado creció alrededor de los ranchos cañeros y, a mediados del siglo XX, la construcción del Ingenio Azucarero “Aarón Sáenz” consolidó su economía. Hoy, Xicoténcatl es un municipio que orgullosamente conserva su tradición agrícola mientras abre sus puertas al ecoturismo, ofreciendo a los visitantes paisajes de ensueño, una gastronomía huasteca única y la calidez de su gente. Es conocido como la “Capital de la Caña” en la región sur de Tamaulipas.

## Geografía
Se localiza en el sur de Tamaulipas, dentro de la región conocida como la Huasteca Tamaulipeca, a los pies de la Sierra Madre Oriental. Presenta un clima cálido subhúmedo, con una temperatura promedio anual de 26°C y una altitud que oscila entre los 80 y 120 metros sobre el nivel del mar. Su territorio combina extensas llanuras dedicadas al cultivo, lomeríos suaves y pequeñas elevaciones. La vegetación predominante es la selva baja caducifolia, pastizales y matorral espinoso. El Río Guayalejo es su principal recurso hídrico, fundamental para el riego de los cañaverales y para la recreación. La fauna local incluye venado cola blanca, armadillo, coyote, garzas, martín pescador y una gran variedad de aves acuáticas. Las lluvias son abundantes en verano, lo que favorece los cultivos.

## Población
