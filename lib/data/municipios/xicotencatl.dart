## Historia
La región que hoy ocupa Xicoténcatl estuvo habitada desde tiempos prehispánicos por grupos huastecos, quienes desarrollaron una avanzada cultura agrícola. Tras la conquista, los españoles introdujeron la caña de azúcar y establecieron las primeras haciendas. Durante la colonia, el valle del Guayalejo fue un importante productor de caña, y para el siglo XIX ya existían trapiches rudimentarios. En 1936 se inició la construcción del Ingenio Azucarero “Aarón Sáenz”, que entró en operación en 1943, transformando por completo la economía y la fisonomía del municipio. Xicoténcatl fue elevado a la categoría de municipio en 1950, separándose de El Mante. A partir de entonces, la caña de azúcar se convirtió en el motor del desarrollo, generando empleos y atrayendo inmigrantes de otras regiones. En las últimas décadas, el municipio ha diversificado su economía con la producción de cítricos y el turismo ecológico.

## Economía
La economía de Xicoténcatl gira en torno a la agroindustria de la caña de azúcar. El Ingenio Azucarero “Aarón Sáenz” es el principal generador de empleos, procesando miles de toneladas de caña al año para producir azúcar estándar, refinada y alcohol. En segundo lugar, destacan los cultivos de maíz, sorgo, frijol y cítricos (naranja, limón y toronja). La ganadería es otra actividad importante, con hatos de ganado bovino y porcino, así como la cría de cabras para la producción de queso. El comercio local se concentra en la cabecera, donde existen tiendas de abarrotes, mercados, talleres mecánicos y negocios de insumos agrícolas. El turismo ecológico ha tomado fuerza gracias al Río Guayalejo y a los balnearios naturales, que atraen visitantes de municipios vecinos.

