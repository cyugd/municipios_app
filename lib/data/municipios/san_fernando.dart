## Historia
San Fernando fue fundado el 19 de marzo de 1749 por José de Escandón como parte de la colonización del Nuevo Santander, bajo el nombre de Villa de San Fernando de la Llave. Originalmente se asentó cerca de la Barra de Salinas, pero debido a inundaciones se trasladó a su ubicación actual. Las primeras familias provenían del Nuevo Reino de León y la actividad económica principal fue la ganadería, complementada con pesca y sal. Durante la época colonial, los franciscanos introdujeron educación y evangelización. San Fernando fue elevada a ciudad en 1980 y ha pasado por diversas etapas históricas: época colonial, Independencia, Revolución Mexicana, siglo XX y siglo XXI, adaptándose a cambios sociales, económicos y culturales.

